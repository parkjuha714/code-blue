#ifndef TRIAGE_H
#define TRIAGE_H

// 자동 트리아지 (Auto Triage) 기능
// 증상 키워드를 기반으로 KTAS 1~5단계를 자동으로 분류합니다.

// KTAS 단계:
//   1단계 (최위급/소생) : 즉각적인 처치 필요 (심정지, 의식없음 등)
//   2단계 (긴급)        : 10분 이내 처치 (심한 가슴통증, 호흡곤란 등)
//   3단계 (응급)        : 30분 이내 처치 (복통, 고열 등)
//   4단계 (준응급)      : 1시간 이내 처치 (두통, 구토 등)
//   5단계 (비응급)      : 2시간 이내 처치 (감기, 찰과상 등)

// 자동 트리아지 함수
// 입력: 증상 문자열 (예: "심한 가슴 통증")
// 출력: KTAS 단계 (1~5)
//       매칭되는 키워드가 없으면 기본값 5 반환
int auto_triage(const char *symptom);

// KTAS 단계명을 문자열로 반환
// 입력: KTAS 단계 (1~5)
// 출력: 단계명 문자열 (예: "최위급", "긴급" 등)
const char *get_ktas_name(int level);

#endif